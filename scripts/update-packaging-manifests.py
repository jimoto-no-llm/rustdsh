#!/usr/bin/env python3
"""Regenerate the Homebrew, Scoop and winget manifests for one released version.

macOS and Windows users can install the published archives through a package
manager, but every manifest pins an exact version, URL and SHA-256, so all five
files have to be refreshed whenever a release is published. This script derives
them from state that is already committed, so no digest is ever typed by hand:

* release-digests.tsv         - the macOS archives (the ledger install.sh reads)
* release-digests-windows.tsv - the Windows archive (the ledger install.ps1 reads)
* CHANGELOG.md                - the release date recorded for that version

It is offline and deterministic: the same registries the installers verify
against produce the same manifests, byte for byte.

Usage:

    python3 scripts/update-packaging-manifests.py                  # latest pinned version
    python3 scripts/update-packaging-manifests.py --version v0.6.0
    python3 scripts/update-packaging-manifests.py --check          # 1 when a file is stale

--check without --version verifies the version the manifests already pin, so a
freshly pinned release does not fail the check until the manifests are
deliberately bumped.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import re
import sys
from pathlib import Path

REPOSITORY = "jimoto-no-llm/rustdsh"
HOMEPAGE = "https://github.com/" + REPOSITORY
PACKAGE_ID = "jimoto-no-llm.rdsh"
WINGET_MANIFEST_VERSION = "1.6.0"
WINGET_SCHEMA = "https://aka.ms/winget-manifest"
UNIX_REGISTRY = "release-digests.tsv"
WINDOWS_REGISTRY = "release-digests-windows.tsv"
CHANGELOG = "CHANGELOG.md"
MAC_ASSETS = ("rdsh-macos-arm64.tar.gz", "rdsh-macos-x64.tar.gz")
WINDOWS_ASSET = "rdsh-windows-x64.zip"
DESCRIPTION = "Fast, safe Rust launcher for DeepSeek Harness (dsh)"
LONG_DESCRIPTION = (
    "rdsh is a Rust launcher for DeepSeek Harness (dsh). It speeds up the "
    "commands used most often (token counting, search, session management and "
    "diagnostics) and delegates conversations and model runs to the original dsh."
)
TAGS = ("cli", "launcher", "deepseek", "dsh", "rust")

HOMEBREW_PATH = "packaging/homebrew/rdsh.rb"
SCOOP_PATH = "packaging/scoop/rdsh.json"
WINGET_DIR = "packaging/winget"
MANIFEST_PATHS = (
    HOMEBREW_PATH,
    SCOOP_PATH,
    WINGET_DIR + "/" + PACKAGE_ID + ".yaml",
    WINGET_DIR + "/" + PACKAGE_ID + ".installer.yaml",
    WINGET_DIR + "/" + PACKAGE_ID + ".locale.en-US.yaml",
)
CHANGELOG_HEADING = re.compile(
    r"^## \[(?P<version>[0-9]+\.[0-9]+\.[0-9]+)\](?: - (?P<date>[0-9]{4}-[0-9]{2}-[0-9]{2}))?\s*$",
    re.MULTILINE,
)


def _load_pin_module():
    """Load scripts/pin-release-digests.py, the owner of the registry format."""
    path = Path(__file__).with_name("pin-release-digests.py")
    spec = importlib.util.spec_from_file_location("pin_release_digests", path)
    if spec is None or spec.loader is None:
        raise SystemExit("cannot load " + str(path))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def normalize_tag(value: str) -> str:
    tag = value if value.startswith("v") else "v" + value
    if not re.fullmatch(r"v[0-9]+\.[0-9]+\.[0-9]+", tag):
        raise SystemExit("unsupported release tag: " + value)
    return tag


def read_registry(root: Path, name: str):
    """Return (latest tag, {version: {asset: sha256}}) for one digest ledger."""
    _comments, latest, versions = _load_pin_module().split_registry(
        (root / name).read_text(encoding="utf-8")
    )
    digests = {version: dict(rows) for version, rows in versions.items()}
    return latest, digests


def asset_digest(digests: dict, tag: str, asset: str, registry: str) -> str:
    try:
        return digests[tag][asset]
    except KeyError:
        raise SystemExit(
            registry + " has no " + asset + " digest for " + tag + ";\n"
            "pin the release first: python3 scripts/pin-release-digests.py " + tag
        ) from None


def release_date(root: Path, tag: str):
    """Return the CHANGELOG date for a released version, or None when undated."""
    text = (root / CHANGELOG).read_text(encoding="utf-8")
    for match in CHANGELOG_HEADING.finditer(text):
        if normalize_tag(match.group("version")) == tag:
            return match.group("date")
    return None


def asset_url(tag: str, asset: str) -> str:
    return HOMEPAGE + "/releases/download/" + tag + "/" + asset


def render_homebrew(tag: str, arm: str, x64: str) -> str:
    version = tag.removeprefix("v")
    return f"""# frozen_string_literal: true

# Homebrew formula for rdsh.
#
# Generated by scripts/update-packaging-manifests.py: bump the version and the
# SHA-256 values through that script instead of editing them here by hand.
class Rdsh < Formula
  desc "{DESCRIPTION}"
  homepage "{HOMEPAGE}"
  version "{version}"
  license "MIT"

  # Only the macOS archives are packaged for Homebrew; Linux and Windows users
  # install through install.sh, Scoop or winget.
  depends_on :macos

  on_macos do
    on_arm do
      url "{asset_url(tag, MAC_ASSETS[0])}"
      sha256 "{arm}"
    end

    on_intel do
      url "{asset_url(tag, MAC_ASSETS[1])}"
      sha256 "{x64}"
    end
  end

  def install
    bin.install "rdsh"
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/rdsh --version")
  end
end
"""


def render_scoop(tag: str, digest: str) -> str:
    manifest = {
        "version": tag.removeprefix("v"),
        "description": DESCRIPTION,
        "homepage": HOMEPAGE,
        "license": "MIT",
        "architecture": {"64bit": {"url": asset_url(tag, WINDOWS_ASSET), "hash": digest}},
        "bin": "rdsh.exe",
        "checkver": {"github": HOMEPAGE},
        "autoupdate": {
            "architecture": {
                "64bit": {
                    "url": HOMEPAGE + "/releases/download/v$version/" + WINDOWS_ASSET
                }
            },
            "hash": {"url": "$baseurl/" + WINDOWS_ASSET + ".sha256"},
        },
    }
    return json.dumps(manifest, indent=4, ensure_ascii=False) + "\n"


def render_winget_version(tag: str) -> str:
    return (
        "# yaml-language-server: $schema=" + WINGET_SCHEMA + ".version."
        + WINGET_MANIFEST_VERSION + ".schema.json\n"
        "PackageIdentifier: " + PACKAGE_ID + "\n"
        "PackageVersion: " + tag.removeprefix("v") + "\n"
        "DefaultLocale: en-US\n"
        "ManifestType: version\n"
        "ManifestVersion: " + WINGET_MANIFEST_VERSION + "\n"
    )


def render_winget_installer(tag: str, digest: str, date) -> str:
    lines = [
        "# yaml-language-server: $schema=" + WINGET_SCHEMA + ".installer."
        + WINGET_MANIFEST_VERSION + ".schema.json",
        "PackageIdentifier: " + PACKAGE_ID,
        "PackageVersion: " + tag.removeprefix("v"),
        "InstallerLocale: en-US",
        "Platform:",
        "  - Windows.Desktop",
        "MinimumOSVersion: 10.0.0.0",
        "InstallerType: zip",
        "NestedInstallerType: portable",
        "NestedInstallerFiles:",
        "  - RelativeFilePath: rdsh.exe",
        "    PortableCommandAlias: rdsh",
        "UpgradeBehavior: install",
    ]
    if date:
        # Quoted on purpose: the winget schema types the field as a string, and a
        # bare YYYY-MM-DD scalar resolves to a timestamp under YAML 1.1.
        lines.append('ReleaseDate: "' + date + '"')
    lines += [
        "Installers:",
        "  - Architecture: x64",
        "    InstallerUrl: " + asset_url(tag, WINDOWS_ASSET),
        "    InstallerSha256: " + digest.upper(),
        "ManifestType: installer",
        "ManifestVersion: " + WINGET_MANIFEST_VERSION,
    ]
    return "\n".join(lines) + "\n"


def render_winget_locale(tag: str) -> str:
    lines = [
        "# yaml-language-server: $schema=" + WINGET_SCHEMA + ".defaultLocale."
        + WINGET_MANIFEST_VERSION + ".schema.json",
        "PackageIdentifier: " + PACKAGE_ID,
        "PackageVersion: " + tag.removeprefix("v"),
        "PackageLocale: en-US",
        "Publisher: jimoto-no-llm",
        "PublisherUrl: https://github.com/jimoto-no-llm",
        "PublisherSupportUrl: " + HOMEPAGE + "/issues",
        "PackageName: rdsh",
        "PackageUrl: " + HOMEPAGE,
        "License: MIT",
        "LicenseUrl: " + HOMEPAGE + "/blob/main/LICENSE",
        "ShortDescription: " + DESCRIPTION,
        "Description: |-",
        "  " + LONG_DESCRIPTION,
        "Moniker: rdsh",
        "Tags:",
    ]
    lines += ["  - " + value for value in TAGS]
    lines += [
        "ReleaseNotesUrl: " + HOMEPAGE + "/releases/tag/" + tag,
        "ManifestType: defaultLocale",
        "ManifestVersion: " + WINGET_MANIFEST_VERSION,
    ]
    return "\n".join(lines) + "\n"


def current_tag(root: Path):
    """The version the committed manifests pin, when one is present."""
    scoop = root / SCOOP_PATH
    if scoop.exists():
        version = json.loads(scoop.read_text(encoding="utf-8")).get("version")
        if isinstance(version, str) and version:
            return "v" + version
    return None


def render_all(root: Path, tag: str):
    _unix_latest, unix = read_registry(root, UNIX_REGISTRY)
    _windows_latest, windows = read_registry(root, WINDOWS_REGISTRY)
    return {
        HOMEBREW_PATH: render_homebrew(
            tag,
            asset_digest(unix, tag, MAC_ASSETS[0], UNIX_REGISTRY),
            asset_digest(unix, tag, MAC_ASSETS[1], UNIX_REGISTRY),
        ),
        SCOOP_PATH: render_scoop(
            tag, asset_digest(windows, tag, WINDOWS_ASSET, WINDOWS_REGISTRY)
        ),
        WINGET_DIR + "/" + PACKAGE_ID + ".yaml": render_winget_version(tag),
        WINGET_DIR + "/" + PACKAGE_ID + ".installer.yaml": render_winget_installer(
            tag, asset_digest(windows, tag, WINDOWS_ASSET, WINDOWS_REGISTRY),
            release_date(root, tag),
        ),
        WINGET_DIR + "/" + PACKAGE_ID + ".locale.en-US.yaml": render_winget_locale(tag),
    }


def check(root: Path, tag: str, contents: dict) -> int:
    stale = []
    for relative, expected in contents.items():
        path = root / relative
        if not path.exists():
            stale.append(relative + " (missing)")
        elif path.read_text(encoding="utf-8") != expected:
            stale.append(relative + " (out of date)")
    if stale:
        for entry in stale:
            print("stale: " + entry, file=sys.stderr)
        print("run: python3 scripts/update-packaging-manifests.py --version " + tag,
              file=sys.stderr)
        return 1
    print("packaging manifests are up to date for " + tag)
    return 0


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="Regenerate the packaging manifests.")
    parser.add_argument(
        "--version", metavar="vX.Y.Z",
        help="release tag to pin (default: the latest pinned one)",
    )
    parser.add_argument(
        "--root", type=Path, default=Path(__file__).resolve().parents[1],
        help="repository root",
    )
    parser.add_argument(
        "--check", action="store_true",
        help="verify the committed files instead of writing them",
    )
    args = parser.parse_args(argv)
    root = args.root.resolve()

    if args.version:
        tag = normalize_tag(args.version)
    elif args.check:
        tag = current_tag(root) or read_registry(root, UNIX_REGISTRY)[0]
    else:
        tag = read_registry(root, UNIX_REGISTRY)[0]
    if not tag:
        raise SystemExit("no version given and no latest row in the digest registry")

    contents = render_all(root, tag)
    if args.check:
        return check(root, tag, contents)
    for relative, text in contents.items():
        path = root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        previous = path.read_text(encoding="utf-8") if path.exists() else None
        if previous != text:
            path.write_text(text, encoding="utf-8")
            print("wrote " + relative + " (" + tag + ")")
    print("packaging manifests are pinned to " + tag)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
