//! Terminal administration surface. Arguments never enter conversation history.
use super::{backend::HarnessBackend, commands, edit, editor, Editor};
use anyhow::{bail, Context, Result};
use crossterm::event::{KeyCode, KeyEvent, KeyEventKind, KeyModifiers};
use ratatui::{
    layout::{Constraint, Direction, Layout, Rect},
    style::{Color, Style},
    text::Line,
    widgets::{Block, Borders, Clear, List, ListItem, ListState, Paragraph},
    Frame,
};
use serde_json::{json, Value};
use std::time::{Duration, Instant};

const MAX_ACTIONS: usize = 4096;
const MAX_DISPLAY: usize = 256 * 1024;

#[derive(Clone)]
struct Action {
    id: String,
    label: String,
    description: String,
    schema: Value,
    defaults: Value,
    sensitive: bool,
    streaming: bool,
}
enum Page {
    Catalog,
    Arguments,
    Confirm { selected: bool },
    Job,
}
pub(super) struct Panel {
    actions: Vec<Action>,
    session_id: Option<String>,
    query: Editor,
    selected: usize,
    action: Option<Action>,
    args: Editor,
    page: Page,
    schema_visible: bool,
    scroll: usize,
    max_scroll: usize,
    follow: bool,
    job_id: Option<String>,
    job: Value,
    next_poll: Instant,
    input: Editor,
    input_open: bool,
    notice: String,
    // Newly supplied secrets may not be known to the backend's redactor yet.
    secrets: Vec<String>,
}

fn bounded(mut value: String, maximum: usize) -> String {
    if value.len() > maximum {
        let mut end = maximum;
        while !value.is_char_boundary(end) {
            end -= 1;
        }
        value.truncate(end);
        value.push_str("\n[表示上限に達したため省略]");
    }
    editor::clean(&value)
}
fn pretty(value: &Value) -> String {
    bounded(
        serde_json::to_string_pretty(value).unwrap_or_default(),
        MAX_DISPLAY,
    )
}
fn secret_schema(schema: &Value) -> bool {
    match schema {
        Value::Object(o) => {
            o.get("writeOnly") == Some(&Value::Bool(true))
                || o.get("format").and_then(Value::as_str) == Some("password")
                || o.iter().any(|(k, v)| {
                    let key = k.to_ascii_lowercase();
                    key.contains("password")
                        || key.contains("apikey")
                        || key.contains("secret")
                        || key.ends_with("token")
                        || secret_schema(v)
                })
        }
        Value::Array(a) => a.iter().any(secret_schema),
        _ => false,
    }
}
fn template(schema: &Value, depth: usize) -> Value {
    if let Some(value) = schema.get("default").or_else(|| schema.get("const")) {
        return value.clone();
    }
    if let Some(value) = schema["enum"].as_array().and_then(|a| a.first()) {
        return value.clone();
    }
    if depth >= 8 {
        return Value::Null;
    }
    if let Some(value) = schema["anyOf"]
        .as_array()
        .or_else(|| schema["oneOf"].as_array())
        .and_then(|a| a.first())
    {
        return template(value, depth + 1);
    }
    match schema["type"].as_str() {
        Some("string") => json!(""),
        Some("integer" | "number") => json!(0),
        Some("boolean") => json!(false),
        Some("array") => json!([]),
        Some("null") => Value::Null,
        _ => {
            let mut result = serde_json::Map::new();
            for key in schema["required"].as_array().into_iter().flatten().take(64) {
                if let Some(key) = key.as_str() {
                    result.insert(key.into(), template(&schema["properties"][key], depth + 1));
                }
            }
            Value::Object(result)
        }
    }
}
fn collect_strings(value: &Value, values: &mut Vec<String>) {
    match value {
        Value::String(s) if !s.is_empty() => values.push(s.clone()),
        Value::Array(a) => a.iter().for_each(|v| collect_strings(v, values)),
        Value::Object(o) => o.values().for_each(|v| collect_strings(v, values)),
        _ => {}
    }
}
// Only fill fields already generated by the required-input template. In
// particular, session/create's optional sessionId must remain absent.
fn fill_session_context(value: &mut Value, session_id: &str) {
    match value {
        Value::Object(fields) => {
            for (name, value) in fields {
                if matches!(name.as_str(), "agentId" | "sessionId") && value.as_str() == Some("") {
                    *value = json!(session_id);
                } else {
                    fill_session_context(value, session_id);
                }
            }
        }
        Value::Array(values) => values
            .iter_mut()
            .for_each(|value| fill_session_context(value, session_id)),
        _ => {}
    }
}

impl Panel {
    pub(super) fn new(value: Value, query: &str) -> Result<Self> {
        let rows = value["actions"]
            .as_array()
            .context("管理操作catalogの形式が不正です")?;
        if rows.len() > MAX_ACTIONS {
            bail!("管理操作catalogが上限4096件を超えています");
        }
        let mut actions = Vec::new();
        for row in rows {
            let id = row["id"]
                .as_str()
                .filter(|s| !s.is_empty() && s.len() <= 512 && !s.chars().any(char::is_control))
                .context("管理操作IDが不正です")?;
            if actions.iter().any(|a: &Action| a.id == id) {
                bail!("管理操作IDが重複しています");
            }
            actions.push(Action {
                id: id.to_owned(),
                label: bounded(row["label"].as_str().unwrap_or(id).into(), 512),
                description: bounded(row["description"].as_str().unwrap_or("").into(), 8192),
                schema: row["schema"].clone(),
                defaults: row["defaults"].clone(),
                sensitive: row["sensitive"] == true
                    || id == "credentials/set"
                    || secret_schema(&row["schema"]),
                streaming: row["mode"] == "stream",
            });
        }
        let mut panel = Self {
            actions,
            session_id: value["sessionId"]
                .as_str()
                .filter(|s| !s.is_empty() && s.len() <= 512 && !s.chars().any(char::is_control))
                .map(str::to_owned),
            query: Editor {
                text: query.into(),
                cursor: query.len(),
            },
            selected: 0,
            action: None,
            args: Editor::default(),
            page: Page::Catalog,
            schema_visible: false,
            scroll: 0,
            max_scroll: 0,
            follow: true,
            job_id: None,
            job: Value::Null,
            next_poll: Instant::now(),
            input: Editor::default(),
            input_open: false,
            notice: String::new(),
            secrets: vec![],
        };
        if let Some(index) = panel.actions.iter().position(|a| a.id == query) {
            panel.select(index)?;
        }
        Ok(panel)
    }
    fn filtered(&self) -> Vec<usize> {
        let query = self.query.text.to_lowercase();
        self.actions
            .iter()
            .enumerate()
            .filter_map(|(i, a)| {
                format!("{} {} {}", a.id, a.label, a.description)
                    .to_lowercase()
                    .contains(&query)
                    .then_some(i)
            })
            .collect()
    }
    fn select(&mut self, index: usize) -> Result<()> {
        let action = self.actions[index].clone();
        let mut value = template(&action.schema, 0);
        if let Some(session_id) = &self.session_id {
            fill_session_context(&mut value, session_id);
        }
        // Explicit catalog defaults override inferred context, including empty
        // strings and nested objects deliberately supplied by the Host.
        if let Some(defaults) = action.defaults.as_object() {
            if let Some(target) = value.as_object_mut() {
                target.extend(defaults.clone());
            }
        }
        let text = serde_json::to_string_pretty(&value)?;
        if text.len() > editor::INPUT_LIMIT {
            bail!("引数テンプレートが16KiBを超えています");
        }
        self.args = Editor {
            cursor: text.len(),
            text,
        };
        self.action = Some(action);
        self.page = Page::Arguments;
        self.schema_visible = false;
        self.scroll = 0;
        self.notice.clear();
        self.secrets.clear();
        Ok(())
    }
    pub(super) fn running(&self) -> bool {
        self.job_id.is_some()
            && matches!(self.job["status"].as_str(), Some("running" | "cancelling"))
    }
    pub(super) fn clear_confirmation(&mut self) {
        if let Page::Confirm { selected } = &mut self.page {
            *selected = false;
        }
    }
    fn redact(&self, backend: &dyn HarnessBackend, value: &str) -> String {
        let mut value = backend.redact(value);
        for secret in &self.secrets {
            value = value.replace(secret, "[REDACTED]");
            // JSON diagnostics can contain escaped copies as well.
            if let Ok(quoted) = serde_json::to_string(secret) {
                value = value.replace(&quoted[1..quoted.len() - 1], "[REDACTED]");
            }
        }
        bounded(value, MAX_DISPLAY)
    }
    pub(super) fn paste(&mut self, value: &str) {
        let accepted = match self.page {
            Page::Catalog => {
                self.selected = 0;
                self.query.insert(value)
            }
            Page::Arguments if !self.schema_visible => self.args.insert(value),
            Page::Job if self.input_open => self.input.insert(value),
            _ => return,
        };
        if !accepted {
            self.notice = "入力は16KiB以内にしてください".into();
        }
    }
    pub(super) fn scroll(&mut self, delta: isize) {
        self.scroll = self
            .scroll
            .saturating_add_signed(delta)
            .min(self.max_scroll);
        self.follow = self.scroll == self.max_scroll;
    }
    pub(super) fn cancel(&mut self, backend: &dyn HarnessBackend) {
        if !self.running() {
            return;
        }
        if let Some(id) = &self.job_id {
            match backend.request("/api/admin/cancel", json!({"jobId":id})) {
                Ok(_) => {
                    self.notice = "中止を要求しました".into();
                    self.next_poll = Instant::now();
                }
                Err(error) => self.notice = self.redact(backend, &error.to_string()),
            }
        }
    }
    pub(super) fn poll(&mut self, backend: &dyn HarnessBackend) {
        if !self.running() || Instant::now() < self.next_poll {
            return;
        }
        self.next_poll = Instant::now() + Duration::from_millis(500);
        let id = self.job_id.as_ref().unwrap();
        let path = format!("/api/admin/job?id={id}");
        match backend.request(&path, json!({"jobId":id})) {
            Ok(mut value) => {
                if !matches!(
                    value["status"].as_str(),
                    Some("running" | "cancelling" | "complete" | "failed" | "cancelled")
                ) {
                    self.job = json!({"status":"failed","error":"管理jobの状態が不正です"});
                    return;
                }
                commands::redact_json_fields(&mut value);
                let redacted = self.redact(backend, &value.to_string());
                self.job = serde_json::from_str(&redacted).unwrap_or_else(|_| {
                    json!({
                        "status":value["status"],"display":redacted
                    })
                });
                self.job["status"] = value["status"].clone();
                self.job["uplink"] = value["uplink"].clone();
            }
            Err(error) => {
                self.notice = self.redact(backend, &error.to_string());
                // A transient failure must not silently mark a remote job complete.
                self.next_poll = Instant::now() + Duration::from_secs(2);
            }
        }
    }
    fn start(&mut self, backend: &dyn HarnessBackend) -> Result<()> {
        let action = self.action.as_ref().context("管理操作がありません")?;
        let args: Value =
            serde_json::from_str(&self.args.text).context("引数は有効なJSONで入力してください")?;
        if !args.is_object() {
            bail!("引数はJSON objectで入力してください");
        }
        if action.sensitive {
            collect_strings(&args, &mut self.secrets);
        }
        let value = backend.request(
            "/api/admin/start",
            json!({"id":action.id,"args":args,"confirmed":true}),
        )?;
        let id = value["jobId"]
            .as_str()
            .filter(|s| {
                !s.is_empty()
                    && s.len() <= 256
                    && s.bytes()
                        .all(|c| c.is_ascii_alphanumeric() || b"_-".contains(&c))
            })
            .context("管理job IDが不正です")?;
        self.job_id = Some(id.to_owned());
        self.job = json!({"id":id,"status":"running","events":[]});
        self.page = Page::Job;
        self.args.clear();
        self.input.clear();
        self.input_open = false;
        self.scroll = 0;
        self.follow = true;
        self.notice.clear();
        self.next_poll = Instant::now();
        Ok(())
    }
    /// True closes the overlay, retaining the current job for /manage to reopen.
    pub(super) fn key(&mut self, key: KeyEvent, backend: &dyn HarnessBackend) -> bool {
        let ctrl = key.modifiers.contains(KeyModifiers::CONTROL);
        if ctrl && key.code == KeyCode::Char('c') {
            if self.running() {
                self.cancel(backend);
            } else {
                self.args.clear();
                self.input.clear();
            }
            return false;
        }
        match &mut self.page {
            Page::Catalog => {
                let ids = self.filtered();
                match key.code {
                    KeyCode::Esc => return true,
                    KeyCode::F(5) => {
                        match backend
                            .request("/api/admin/catalog", json!({}))
                            .and_then(|value| Self::new(value, &self.query.text))
                        {
                            Ok(panel) => *self = panel,
                            Err(error) => self.notice = self.redact(backend, &error.to_string()),
                        }
                    }
                    KeyCode::Up => self.selected = self.selected.saturating_sub(1),
                    KeyCode::Down => {
                        self.selected = (self.selected + 1).min(ids.len().saturating_sub(1))
                    }
                    KeyCode::PageUp => self.selected = self.selected.saturating_sub(8),
                    KeyCode::PageDown => {
                        self.selected = (self.selected + 8).min(ids.len().saturating_sub(1))
                    }
                    KeyCode::Enter if key.kind == KeyEventKind::Press => {
                        if let Some(&id) = ids.get(self.selected) {
                            if let Err(error) = self.select(id) {
                                self.notice = error.to_string();
                            }
                        }
                    }
                    _ => {
                        edit(&mut self.query, key);
                        self.selected = 0;
                    }
                }
            }
            Page::Arguments => match key.code {
                KeyCode::Esc => {
                    self.args.clear();
                    self.page = Page::Catalog;
                    self.notice.clear();
                }
                KeyCode::F(2) => {
                    self.schema_visible = !self.schema_visible;
                    self.scroll = 0;
                }
                KeyCode::Char('s') if ctrl && key.kind == KeyEventKind::Press => {
                    match serde_json::from_str::<Value>(&self.args.text) {
                        Ok(value) if value.is_object() => {
                            self.page = Page::Confirm { selected: false };
                            self.scroll = 0;
                            self.notice.clear();
                        }
                        _ => self.notice = "引数は有効なJSON objectで入力してください".into(),
                    }
                }
                KeyCode::PageUp if self.schema_visible => self.scroll(-8),
                KeyCode::PageDown if self.schema_visible => self.scroll(8),
                KeyCode::Up if self.schema_visible => self.scroll(-1),
                KeyCode::Down if self.schema_visible => self.scroll(1),
                KeyCode::Enter if !self.schema_visible => {
                    self.args.insert("\n");
                }
                _ if !self.schema_visible && !edit(&mut self.args, key) => {
                    self.notice = "入力は16KiB以内にしてください".into();
                }
                _ => {}
            },
            Page::Confirm { selected } => match key.code {
                KeyCode::Tab | KeyCode::BackTab | KeyCode::Left | KeyCode::Right => {
                    *selected = !*selected
                }
                KeyCode::Esc => self.page = Page::Arguments,
                KeyCode::PageUp | KeyCode::Up => self.scroll(-3),
                KeyCode::PageDown | KeyCode::Down => self.scroll(3),
                KeyCode::Enter if key.kind == KeyEventKind::Press => {
                    if !*selected {
                        self.page = Page::Arguments;
                    } else if let Err(error) = self.start(backend) {
                        self.notice = self.redact(backend, &error.to_string());
                        self.clear_confirmation();
                    }
                }
                _ => {}
            },
            Page::Job => {
                if self.input_open {
                    match key.code {
                        KeyCode::Esc => {
                            self.input_open = false;
                            self.input.clear();
                        }
                        KeyCode::Char('s') if ctrl && key.kind == KeyEventKind::Press => {
                            let value = serde_json::from_str::<Value>(&self.input.text);
                            match value {
                                Ok(value) => match backend.request(
                                    "/api/admin/input",
                                    json!({"jobId":self.job_id,"value":value}),
                                ) {
                                    Ok(_) => {
                                        self.input.clear();
                                        self.input_open = false;
                                        self.notice = "入力を送信しました".into();
                                    }
                                    Err(error) => {
                                        self.notice = self.redact(backend, &error.to_string())
                                    }
                                },
                                Err(_) => {
                                    self.notice = "送信内容は有効なJSONで入力してください".into()
                                }
                            }
                        }
                        KeyCode::Enter => {
                            self.input.insert("\n");
                        }
                        _ => {
                            edit(&mut self.input, key);
                        }
                    }
                } else {
                    match key.code {
                        KeyCode::Esc => return true,
                        KeyCode::Char('b') if !self.running() => {
                            self.page = Page::Catalog;
                            self.secrets.clear();
                        }
                        KeyCode::Char('i') if self.running() && self.job["uplink"] == true => {
                            self.input_open = true;
                            self.input.clear();
                        }
                        KeyCode::Up => self.scroll(-1),
                        KeyCode::Down => self.scroll(1),
                        KeyCode::PageUp => self.scroll(-8),
                        KeyCode::PageDown => self.scroll(8),
                        KeyCode::Home => {
                            self.scroll = 0;
                            self.follow = false;
                        }
                        KeyCode::End => {
                            self.scroll = self.max_scroll;
                            self.follow = true;
                        }
                        _ => {}
                    }
                }
            }
        }
        false
    }
    fn text_panel(&mut self, frame: &mut Frame, area: Rect, content: &str, follow: bool) {
        let wrapped = editor::wrap(
            &editor::clean(content),
            area.width.saturating_sub(1),
            usize::MAX,
        )
        .0;
        self.max_scroll = wrapped.len().saturating_sub(area.height as usize);
        if follow && self.follow {
            self.scroll = self.max_scroll;
        }
        self.scroll = self.scroll.min(self.max_scroll);
        frame.render_widget(
            Paragraph::new(
                wrapped
                    .into_iter()
                    .skip(self.scroll)
                    .take(area.height as usize)
                    .map(Line::raw)
                    .collect::<Vec<_>>(),
            ),
            area,
        );
    }
    pub(super) fn draw(&mut self, frame: &mut Frame, area: Rect) {
        let area = Rect::new(
            area.x + 1,
            area.y + 1,
            area.width.saturating_sub(2),
            area.height.saturating_sub(2),
        );
        frame.render_widget(Clear, area);
        let outer = Block::default()
            .borders(Borders::ALL)
            .title(" DSH 管理 ")
            .border_style(Style::default().fg(Color::Cyan));
        let inner = outer.inner(area);
        frame.render_widget(outer, area);
        let rows = Layout::default()
            .direction(Direction::Vertical)
            .constraints([
                Constraint::Length(2),
                Constraint::Min(1),
                Constraint::Length(3),
            ])
            .split(inner);
        let title = self
            .action
            .as_ref()
            .map(|a| format!("{}{}", a.id, if a.streaming { " · stream" } else { "" }))
            .unwrap_or_default();
        let help = match self.page {
            Page::Catalog => "↑↓ 選択 · Enter 編集 · 文字で検索\nF5 更新 · Esc 閉じる",
            Page::Arguments => "Enter 改行 · Ctrl+S 確認\nCtrl+U 消去 · F2 schema · Esc 一覧",
            Page::Confirm { .. } => "Tab 選択 · Enter 決定\n↑↓/PgUp/Dn 本文 · Esc 編集",
            Page::Job if self.input_open => "JSON入力 · Ctrl+S 送信\nEnter 改行 · Esc 入力を閉じる",
            Page::Job if self.job["uplink"] == true => {
                "Ctrl+C 中止 · i 入力 · b 一覧\nPgUp/Dn 閲覧 · Esc 閉じる"
            }
            Page::Job => "Ctrl+C 中止 · b 一覧\nPgUp/Dn 閲覧 · Esc 閉じる",
        };
        let mut footer = vec![Line::styled(
            editor::clean(&self.notice),
            Style::default().fg(Color::Yellow),
        )];
        footer.extend(help.split('\n').map(Line::raw));
        let mut header = title;
        match &self.page {
            Page::Catalog => {
                let ids = self.filtered();
                header = format!(
                    "検索: {}\n{} / {} 操作",
                    self.query.text,
                    ids.len(),
                    self.actions.len()
                );
                let entries = ids
                    .iter()
                    .map(|i| {
                        let a = &self.actions[*i];
                        ListItem::new(format!(
                            "{}{}  {}",
                            a.id,
                            if a.streaming { " [stream]" } else { "" },
                            a.label
                        ))
                    })
                    .collect::<Vec<_>>();
                let mut state = ListState::default().with_selected(
                    (!ids.is_empty()).then_some(self.selected.min(ids.len().saturating_sub(1))),
                );
                frame.render_stateful_widget(
                    List::new(entries)
                        .highlight_symbol("▶ ")
                        .highlight_style(Style::default().fg(Color::Black).bg(Color::Cyan)),
                    rows[1],
                    &mut state,
                );
            }
            Page::Arguments => {
                let action = self.action.as_ref().unwrap();
                if self.schema_visible {
                    let content = format!(
                        "{}\n\n入力schema:\n{}",
                        action.description,
                        pretty(&action.schema)
                    );
                    self.text_panel(frame, rows[1], &content, false);
                } else {
                    header.push_str(if action.sensitive {
                        "\n秘密入力: 全体をマスク · 履歴には保存しません"
                    } else {
                        "\n引数JSON · ファイル: {\"$file\":\"/path\"}"
                    });
                    draw_editor(frame, rows[1], &self.args, action.sensitive);
                }
            }
            Page::Confirm { selected } => {
                let selected = *selected;
                let action = self.action.as_ref().unwrap();
                let mut value: Value = serde_json::from_str(&self.args.text).unwrap_or(Value::Null);
                commands::redact_json_fields(&mut value);
                let content = format!(
                    "{}\n\nこの操作を実行します。\n{}\n\n{}",
                    action.description,
                    action.id,
                    if action.sensitive {
                        "[秘密を含む引数は非表示]".into()
                    } else {
                        pretty(&value)
                    }
                );
                self.text_panel(frame, rows[1], &content, false);
                footer[0] = Line::styled(
                    if selected {
                        "  戻る      ▶ 実行する"
                    } else {
                        "▶ 戻る        実行する"
                    },
                    Style::default().fg(Color::Yellow),
                );
                if !self.notice.is_empty() {
                    header.push_str(&format!("\n{}", self.notice));
                }
            }
            Page::Job => {
                header.push_str(&format!(
                    "\n状態: {}",
                    self.job["status"].as_str().unwrap_or("不明")
                ));
                if self.input_open {
                    draw_editor(
                        frame,
                        rows[1],
                        &self.input,
                        self.action.as_ref().is_some_and(|a| a.sensitive),
                    );
                } else {
                    let content = pretty(&self.job);
                    self.text_panel(frame, rows[1], &content, true);
                }
            }
        }
        frame.render_widget(Paragraph::new(header), rows[0]);
        frame.render_widget(Paragraph::new(footer), rows[2]);
    }
}

fn draw_editor(frame: &mut Frame, area: Rect, input: &Editor, masked: bool) {
    let (text, cursor) = if masked {
        let cursor = input.text[..input.cursor].chars().count();
        let text: String = input
            .text
            .chars()
            .map(|c| if c == '\n' { '\n' } else { '*' })
            .collect();
        (text, cursor)
    } else {
        (input.text.clone(), input.cursor)
    };
    let (wrapped, (x, y)) = editor::wrap(&text, area.width.saturating_sub(1), cursor);
    let start = y.saturating_sub(area.height.saturating_sub(1));
    frame.render_widget(
        Paragraph::new(
            wrapped
                .into_iter()
                .skip(start as usize)
                .map(Line::raw)
                .collect::<Vec<_>>(),
        ),
        area,
    );
    frame.set_cursor_position((
        area.x + x.min(area.width.saturating_sub(1)),
        area.y + y.saturating_sub(start).min(area.height.saturating_sub(1)),
    ));
}

